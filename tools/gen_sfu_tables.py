#!/usr/bin/env python3
"""Generate the normative MGPU-32 SFU coefficient tables.

For every table and every one of its 128 segments, a quadratic in the local offset u is
fitted through the three Chebyshev nodes of the segment. C1 and C2 are quantized, and C0
is then re-centred against the exact integer datapath so the error is balanced.
All arithmetic uses Decimal at 60 digits or plain integers, so the output is identical on
every machine.

Writes:
  spec/sfu/<table>.txt             normative tables (hex)
  python/mgpu/fp/sfu_tables.py     generated Python mirror

Usage: gen_sfu_tables.py [--check]
"""

import argparse
import sys
from decimal import Decimal, getcontext, ROUND_HALF_EVEN, ROUND_FLOOR
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
getcontext().prec = 60

SEG_BITS = 7
SEGS = 1 << SEG_BITS
Y_FRAC, C1_FRAC, C2_FRAC = 30, 22, 16
C0_BITS, C1_BITS, C2_BITS = 32, 24, 18   # C0 unsigned, C1/C2 two's complement

LN2 = Decimal(2).ln()
ONE = Decimal(1)


def log2(v):
    return v.ln() / LN2


FUNCS = {
    "rcp":          (23, "1 / (1 + t)",                    lambda t: ONE / (1 + t)),
    "rsqrt_even":   (23, "1 / sqrt(1 + t)",                lambda t: ONE / (1 + t).sqrt()),
    "rsqrt_odd":    (23, "1 / sqrt(2 * (1 + t))",          lambda t: ONE / (2 * (1 + t)).sqrt()),
    "exp2":         (30, "2^t",                            lambda t: (t * LN2).exp()),
    "log2":         (23, "log2(1 + t)",                    lambda t: log2(1 + t)),
    "log2_near_hi": (23, "log2(1 + t) / t",                lambda t: log2(1 + t) / t if t else 1 / LN2),
    "log2_near_lo": (23, "log2(x) / (x - 1), x = (1+t)/2", lambda t: log2((1 + t) / 2) / ((1 + t) / 2 - 1)),
}


def q(v: Decimal, frac: int) -> int:
    return int((v * (1 << frac)).to_integral_value(ROUND_HALF_EVEN))


def datapath(c0, c1, c2, d, d_bits):
    """Must match mgpu.fp.sfu.poly exactly."""
    sq = (d * d) >> (2 * d_bits - 16)
    return c0 + ((c1 * d) >> (d_bits - 1)) + ((c2 * sq) >> 16)


def fit(name):
    t_bits, _, f = FUNCS[name]
    d_bits = t_bits - SEG_BITS
    h = Decimal(1) / SEGS
    r3 = Decimal(3).sqrt() / 2
    nodes = [h / 2 * (1 + r3), h / 2, h / 2 * (1 - r3)]
    rows = []
    for i in range(SEGS):
        t0 = Decimal(i) / SEGS
        ys = [f(t0 + u) for u in nodes]
        # Newton divided differences -> monomial coefficients in u.
        u0, u1, u2 = nodes
        a1 = (ys[1] - ys[0]) / (u1 - u0)
        a2 = ((ys[2] - ys[1]) / (u2 - u1) - a1) / (u2 - u0)
        c2 = a2
        c1 = a1 - a2 * (u0 + u1)
        c0 = ys[0] - a1 * u0 + a2 * u0 * u1
        C1, C2 = q(c1, C1_FRAC), q(c2, C2_FRAC)
        C0 = q(c0, Y_FRAC)
        # Re-centre C0 against the integer datapath on 65 sample points.
        top = (1 << d_bits) - 1
        samples = sorted({(top * k) // 64 for k in range(65)})
        errs = []
        scale = Decimal(1 << Y_FRAC)
        for d in samples:
            t = t0 + Decimal(d) / (1 << t_bits)
            errs.append(f(t) * scale - datapath(C0, C1, C2, d, d_bits))
        C0 += int(((max(errs) + min(errs)) / 2).to_integral_value(ROUND_FLOOR))
        assert 0 <= C0 < (1 << C0_BITS), (name, i, C0)
        assert -(1 << (C1_BITS - 1)) <= C1 < (1 << (C1_BITS - 1)), (name, i, C1)
        assert -(1 << (C2_BITS - 1)) <= C2 < (1 << (C2_BITS - 1)), (name, i, C2)
        rows.append((C0, C1, C2))
    return rows


def table_text(name, rows):
    t_bits, desc, _ = FUNCS[name]
    out = [f"# MGPU-32 SFU table '{name}': F(t) = {desc}, t in [0,1), T is {t_bits} bits",
           "# Generated by tools/gen_sfu_tables.py -- normative, do not edit.",
           f"# columns: index C0 (u{C0_BITS}, *2^-{Y_FRAC})  C1 (s{C1_BITS}, *2^-{C1_FRAC})"
           f"  C2 (s{C2_BITS}, *2^-{C2_FRAC}), two's complement hex"]
    for i, (c0, c1, c2) in enumerate(rows):
        out.append(f"{i:02x} {c0:08x} {c1 & ((1 << C1_BITS) - 1):06x} {c2 & ((1 << C2_BITS) - 1):05x}")
    return "\n".join(out) + "\n"


def py_text(all_rows):
    out = ['"""Generated by tools/gen_sfu_tables.py from spec/sfu/*.txt. Do not edit."""', "",
           "TABLES = {"]
    for name, rows in all_rows.items():
        out.append(f"    {name!r}: (")
        for c0, c1, c2 in rows:
            out.append(f"        ({c0:#010x}, {c1}, {c2}),")
        out.append("    ),")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify committed files are up to date")
    args = ap.parse_args()
    all_rows = {name: fit(name) for name in FUNCS}
    files = {ROOT / "spec" / "sfu" / f"{n}.txt": table_text(n, r) for n, r in all_rows.items()}
    files[ROOT / "python" / "mgpu" / "fp" / "sfu_tables.py"] = py_text(all_rows)
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        sys.exit(1 if stale else 0)
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"wrote {len(files)} files ({len(stale)} changed)")


if __name__ == "__main__":
    main()
