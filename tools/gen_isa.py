#!/usr/bin/env python3
"""Validate spec/isa.toml and generate the derived ISA files from it.

Generates:
  python/mgpu/isa/tables.py        Python mirror of the TOML
  docs/isa/encoding-tables.md      opcode map, funct tables and bit patterns

It also checks the conformance encodings listed in the TOML. Later phases extend it with
Rust and SystemVerilog outputs.

Usage: gen_isa.py [--check]
"""

import argparse
import pprint
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "isa.toml"
TOKENS = {"sd", "sa", "sb", "sc", "st", "vd", "va", "vb", "vc", "vt", "vb|sb", "shamt",
          "simm16", "uimm16", "simm16(sa)", "simm16(va)", "sr", "target16", "target26"}
FIELD_OF = {"d": "rd", "t": "rd", "a": "ra", "b": "rb", "c": "rc"}


def load():
    with open(SPEC, "rb") as fh:
        return tomllib.load(fh)


def token_fields(tok):
    if tok in ("simm16", "uimm16", "target16"):
        return ["imm16"]
    if tok == "target26":
        return ["offset26"]
    if tok == "sr":
        return ["ra"]
    if tok == "shamt" or tok == "vb|sb":
        return ["rb"]
    if "(" in tok:
        return ["imm16", "ra"]
    return [FIELD_OF[tok[-1]]]


def validate(spec):
    errors = []
    opcodes, mnemonics = set(), set()
    fmt_fields = {k: {f[0] for f in v["fields"]} for k, v in spec["formats"].items()}
    for g in spec["group"]:
        if g["opcode"] in opcodes:
            errors.append(f"duplicate opcode {g['opcode']:#x}")
        opcodes.add(g["opcode"])
        if not 0 <= g["opcode"] < 64:
            errors.append(f"{g['name']}: opcode out of range")
        functs = set()
        width = {"R": 10, "R4": 5}.get(g["format"])
        for i in g["instructions"]:
            mn = i["mnemonic"]
            if mn in mnemonics:
                errors.append(f"duplicate mnemonic {mn}")
            mnemonics.add(mn)
            if width is None:
                if "funct" in i or len(g["instructions"]) != 1:
                    errors.append(f"{mn}: I/J groups hold exactly one instruction and no funct")
            else:
                f = i.get("funct")
                if f is None or not 0 <= f < (1 << width) or f in functs:
                    errors.append(f"{mn}: bad or duplicate funct {f}")
                functs.add(f)
            used = []
            for tok in (t.strip() for t in i["syntax"].split(",") if t.strip()):
                if tok not in TOKENS:
                    errors.append(f"{mn}: unknown operand token {tok!r}")
                    continue
                for fld in token_fields(tok):
                    if fld not in fmt_fields[g["format"]]:
                        errors.append(f"{mn}: token {tok} needs field {fld} absent in {g['format']}")
                    if fld in used:
                        errors.append(f"{mn}: field {fld} used twice")
                    used.append(fld)
    ids = [s["id"] for s in spec["sr"]]
    if len(set(ids)) != len(ids):
        errors.append("duplicate SR id")
    for s in spec["sr"]:
        if (s["kind"] == "uniform") != (s["id"] < 16):
            errors.append(f"SR {s['name']}: uniform SRs must have id < 16, per-lane SRs id >= 16")
    return errors


def py_text(spec):
    body = {k: spec[k] for k in ("meta", "formats", "group", "sr", "pseudo", "vector")}
    return ('"""Generated by tools/gen_isa.py from spec/isa.toml. Do not edit."""\n\n'
            f"META = {pprint.pformat(body['meta'], sort_dicts=False)}\n\n"
            f"FORMATS = {pprint.pformat(body['formats'], sort_dicts=False)}\n\n"
            f"GROUPS = {pprint.pformat(body['group'], sort_dicts=False, width=110)}\n\n"
            f"SRS = {pprint.pformat(body['sr'], sort_dicts=False)}\n\n"
            f"PSEUDOS = {pprint.pformat(body['pseudo'], sort_dicts=False, width=110)}\n\n"
            f"VECTORS = {pprint.pformat(body['vector'], sort_dicts=False)}\n")


def bit_pattern(g, i):
    op = format(g["opcode"], "06b")
    fmt = g["format"]
    syn = [t.strip() for t in i["syntax"].split(",") if t.strip()]
    used = {f for t in syn for f in token_fields(t)}
    sb_live = "vb|sb" in syn
    fld = lambda name, ch: ch * 5 if name in used else "-----"  # noqa: E731
    if fmt == "R":
        sb = "S" if sb_live else "-"
        return f"{op} {fld('rd', 'd')} {fld('ra', 'a')} {fld('rb', 'b')} {sb} {i['funct']:010b}"
    if fmt == "R4":
        return (f"{op} {fld('rd', 'd')} {fld('ra', 'a')} {fld('rb', 'b')} {fld('rc', 'c')} "
                f"{'S' if sb_live else '-'} {i['funct']:05b}")
    if fmt == "I":
        return f"{op} {fld('rd', 'd')} {fld('ra', 'a')} {'i' * 16}"
    return f"{op} {'o' * 26}"


def doc_text(spec):
    out = ["# MGPU-32 encoding tables", "",
           "> Generated by `tools/gen_isa.py` from `spec/isa.toml`. Do not edit by hand.", "",
           "Bit-pattern legend: `d`/`a`/`b`/`c` are the rd/ra/rb/rc register fields, `S` is the "
           "scalar-broadcast bit, `i` is imm16 and `o` is offset26. Fixed bits are shown literally. "
           "`-` marks a field the instruction ignores; it must be written as 0 and is ignored on "
           "decode (rule DEC-2).", "",
           "## Opcode map", "",
           "| Opcode | Group | Format | Exec | Unit |", "|---|---|---|---|---|"]
    by_op = {g["opcode"]: g for g in spec["group"]}
    for op in range(64):
        if op in by_op:
            g = by_op[op]
            out.append(f"| `0x{op:02X}` | {g['name']} | {g['format']} | {g['exec']} | {g['unit']} |")
    out += ["", "All other opcodes (0x0E, 0x0F, 0x17-0x1F, 0x23-0x2F, and 0x30-0x3F, which is "
            "reserved for extensions) decode as an illegal instruction (error 1).", "",
            "## Instructions", ""]
    for g in spec["group"]:
        out += [f"### {g['name']} (opcode `0x{g['opcode']:02X}`, format {g['format']})", "",
                "| Mnemonic | funct | Syntax | Exec | Unit | Bit pattern |", "|---|---|---|---|---|---|"]
        for i in g["instructions"]:
            f = f"`0x{i['funct']:02X}`" if "funct" in i else "-"
            out.append(f"| `{i['mnemonic']}` | {f} | `{i['mnemonic']} {i['syntax']}` | "
                       f"{i.get('exec', g['exec'])} | {i.get('unit', g['unit'])} | "
                       f"`{bit_pattern(g, i)}` |")
        if g["format"] in ("R", "R4"):
            out += ["", "Any other funct value in this group is illegal."]
        out.append("")
    out += ["## Special registers", "", "| ID | Name | Kind |", "|---|---|---|"]
    for s in spec["sr"]:
        out.append(f"| {s['id']} | `{s['name']}` | {s['kind']} |")
    out += ["", "## Pseudo-instructions", "", "| Pseudo | Expansion |", "|---|---|"]
    for p in spec["pseudo"]:
        out.append(f"| `{p['mnemonic']} {p['syntax']}` | `{'` ; `'.join(p['expansion'])}` |")
    out += ["", "## Conformance encodings", "", "| Assembly | Hex |", "|---|---|"]
    for v in spec["vector"]:
        out.append(f"| `{v['asm']}` | `0x{v['hex']:08X}` |")
    return "\n".join(out) + "\n"


def check_vectors(spec):
    sys.path.insert(0, str(ROOT / "python"))
    from mgpu.isa import assemble_one, decode
    errs = []
    for v in spec["vector"]:
        w = assemble_one(v["asm"])
        if w != v["hex"]:
            errs.append(f"vector {v['asm']!r}: got {w:#010x}, expected {v['hex']:#010x}")
        if decode(w).instr.mnemonic != v["asm"].split()[0].upper():
            errs.append(f"vector {v['asm']!r}: decode mismatch")
    return errs


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = ap.parse_args()
    spec = load()
    errors = validate(spec)
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    files = {ROOT / "python/mgpu/isa/tables.py": py_text(spec),
             ROOT / "docs/isa/encoding-tables.md": doc_text(spec)}
    stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
    else:
        for p, t in files.items():
            p.write_text(t)
    errors = check_vectors(spec)  # after writing, so tables.py is current
    for e in errors:
        print(e)
    n = sum(len(g["instructions"]) for g in spec["group"])
    print(f"{len(spec['group'])} opcodes, {n} instructions, {len(spec['vector'])} vectors checked"
          + ("" if args.check else f", {len(stale)} file(s) updated"))
    sys.exit(1 if errors or (args.check and stale) else 0)


if __name__ == "__main__":
    main()
