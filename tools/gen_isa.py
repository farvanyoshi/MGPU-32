#!/usr/bin/env python3
"""Validate spec/isa.toml and generate the derived ISA files from it.

Generates:
  python/mgpu/isa/tables.py        Python mirror of the TOML
  docs/isa/encoding-tables.md      opcode map, funct tables and bit patterns
  rust/mgpu-core/src/isa_gen.rs    Rust Op enum, mnemonics and decoder ([DEC-1])
  rtl/pkg/mgpu_isa_pkg.sv          SystemVerilog op enum, unit classes and decoder ([DEC-1])

It also checks the conformance encodings listed in the TOML.

Usage: gen_isa.py [--check]
"""

import argparse
import pprint
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "isa.toml"
TOKENS = {"sd", "sa", "sb", "sc", "st", "vd", "va", "vb", "vc", "vt", "vb|sb", "shamt",
          "simm16", "uimm16", "simm16(sa)", "simm16(va)", "sr", "target16", "target26"}
FIELD_OF = {"d": "rd", "t": "rd", "a": "ra", "b": "rb", "c": "rc"}


def load():
    with open(SPEC, "rb") as fh:
        return tomllib.load(fh)


def token_fields(tok):
    if tok in ("simm16", "uimm16", "target16"):
        return ["imm16"]
    if tok == "target26":
        return ["offset26"]
    if tok == "sr":
        return ["ra"]
    if tok == "shamt" or tok == "vb|sb":
        return ["rb"]
    if "(" in tok:
        return ["imm16", "ra"]
    return [FIELD_OF[tok[-1]]]


def validate(spec):
    errors = []
    opcodes, mnemonics = set(), set()
    fmt_fields = {k: {f[0] for f in v["fields"]} for k, v in spec["formats"].items()}
    for g in spec["group"]:
        if g["opcode"] in opcodes:
            errors.append(f"duplicate opcode {g['opcode']:#x}")
        opcodes.add(g["opcode"])
        if not 0 <= g["opcode"] < 64:
            errors.append(f"{g['name']}: opcode out of range")
        functs = set()
        width = {"R": 10, "R4": 5}.get(g["format"])
        for i in g["instructions"]:
            mn = i["mnemonic"]
            if mn in mnemonics:
                errors.append(f"duplicate mnemonic {mn}")
            mnemonics.add(mn)
            if width is None:
                if "funct" in i or len(g["instructions"]) != 1:
                    errors.append(f"{mn}: I/J groups hold exactly one instruction and no funct")
            else:
                f = i.get("funct")
                if f is None or not 0 <= f < (1 << width) or f in functs:
                    errors.append(f"{mn}: bad or duplicate funct {f}")
                functs.add(f)
            used = []
            for tok in (t.strip() for t in i["syntax"].split(",") if t.strip()):
                if tok not in TOKENS:
                    errors.append(f"{mn}: unknown operand token {tok!r}")
                    continue
                for fld in token_fields(tok):
                    if fld not in fmt_fields[g["format"]]:
                        errors.append(f"{mn}: token {tok} needs field {fld} absent in {g['format']}")
                    if fld in used:
                        errors.append(f"{mn}: field {fld} used twice")
                    used.append(fld)
    ids = [s["id"] for s in spec["sr"]]
    if len(set(ids)) != len(ids):
        errors.append("duplicate SR id")
    for s in spec["sr"]:
        if (s["kind"] == "uniform") != (s["id"] < 16):
            errors.append(f"SR {s['name']}: uniform SRs must have id < 16, per-lane SRs id >= 16")
    return errors


def py_text(spec):
    body = {k: spec[k] for k in ("meta", "formats", "group", "sr", "pseudo", "vector")}
    return ('"""Generated by tools/gen_isa.py from spec/isa.toml. Do not edit."""\n\n'
            f"META = {pprint.pformat(body['meta'], sort_dicts=False)}\n\n"
            f"FORMATS = {pprint.pformat(body['formats'], sort_dicts=False)}\n\n"
            f"GROUPS = {pprint.pformat(body['group'], sort_dicts=False, width=110)}\n\n"
            f"SRS = {pprint.pformat(body['sr'], sort_dicts=False)}\n\n"
            f"PSEUDOS = {pprint.pformat(body['pseudo'], sort_dicts=False, width=110)}\n\n"
            f"VECTORS = {pprint.pformat(body['vector'], sort_dicts=False)}\n")


def bit_pattern(g, i):
    op = format(g["opcode"], "06b")
    fmt = g["format"]
    syn = [t.strip() for t in i["syntax"].split(",") if t.strip()]
    used = {f for t in syn for f in token_fields(t)}
    sb_live = "vb|sb" in syn
    fld = lambda name, ch: ch * 5 if name in used else "-----"  # noqa: E731
    if fmt == "R":
        sb = "S" if sb_live else "-"
        return f"{op} {fld('rd', 'd')} {fld('ra', 'a')} {fld('rb', 'b')} {sb} {i['funct']:010b}"
    if fmt == "R4":
        return (f"{op} {fld('rd', 'd')} {fld('ra', 'a')} {fld('rb', 'b')} {fld('rc', 'c')} "
                f"{'S' if sb_live else '-'} {i['funct']:05b}")
    if fmt == "I":
        return f"{op} {fld('rd', 'd')} {fld('ra', 'a')} {'i' * 16}"
    return f"{op} {'o' * 26}"


def doc_text(spec):
    out = ["# MGPU-32 encoding tables", "",
           "> Generated by `tools/gen_isa.py` from `spec/isa.toml`. Do not edit by hand.", "",
           "Bit-pattern legend: `d`/`a`/`b`/`c` are the rd/ra/rb/rc register fields, `S` is the "
           "scalar-broadcast bit, `i` is imm16 and `o` is offset26. Fixed bits are shown literally. "
           "`-` marks a field the instruction ignores; it must be written as 0 and is ignored on "
           "decode (rule DEC-2).", "",
           "## Opcode map", "",
           "| Opcode | Group | Format | Exec | Unit |", "|---|---|---|---|---|"]
    by_op = {g["opcode"]: g for g in spec["group"]}
    for op in range(64):
        if op in by_op:
            g = by_op[op]
            out.append(f"| `0x{op:02X}` | {g['name']} | {g['format']} | {g['exec']} | {g['unit']} |")
    out += ["", "All other opcodes (0x0E, 0x0F, 0x17-0x1F, 0x23-0x2F, and 0x30-0x3F, which is "
            "reserved for extensions) decode as an illegal instruction (error 1).", "",
            "## Instructions", ""]
    for g in spec["group"]:
        out += [f"### {g['name']} (opcode `0x{g['opcode']:02X}`, format {g['format']})", "",
                "| Mnemonic | funct | Syntax | Exec | Unit | Bit pattern |", "|---|---|---|---|---|---|"]
        for i in g["instructions"]:
            f = f"`0x{i['funct']:02X}`" if "funct" in i else "-"
            out.append(f"| `{i['mnemonic']}` | {f} | `{i['mnemonic']} {i['syntax']}` | "
                       f"{i.get('exec', g['exec'])} | {i.get('unit', g['unit'])} | "
                       f"`{bit_pattern(g, i)}` |")
        if g["format"] in ("R", "R4"):
            out += ["", "Any other funct value in this group is illegal."]
        out.append("")
    out += ["## Special registers", "", "| ID | Name | Kind |", "|---|---|---|"]
    for s in spec["sr"]:
        out.append(f"| {s['id']} | `{s['name']}` | {s['kind']} |")
    out += ["", "## Pseudo-instructions", "", "| Pseudo | Expansion |", "|---|---|"]
    for p in spec["pseudo"]:
        out.append(f"| `{p['mnemonic']} {p['syntax']}` | `{'` ; `'.join(p['expansion'])}` |")
    out += ["", "## Conformance encodings", "", "| Assembly | Hex |", "|---|---|"]
    for v in spec["vector"]:
        out.append(f"| `{v['asm']}` | `0x{v['hex']:08X}` |")
    return "\n".join(out) + "\n"


def rust_variant(mnemonic):
    return "".join(p[:1].upper() + p[1:].lower() for p in mnemonic.replace(".", "_").split("_"))


def rust_text(spec):
    instrs = [(g, i) for g in spec["group"] for i in g["instructions"]]
    out = ["// Generated by tools/gen_isa.py from spec/isa.toml. Do not edit.", "",
           "/// Every MGPU-32 instruction, in spec/isa.toml order.",
           "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]", "pub enum Op {"]
    out += [f"    {rust_variant(i['mnemonic'])}," for _, i in instrs]
    out += ["}", "", f"pub const NUM_OPS: usize = {len(instrs)};", "",
            "/// Assembly mnemonic of each Op, indexed by `op as usize`.",
            "pub const MNEMONICS: [&str; NUM_OPS] = ["]
    out += [f'    "{i["mnemonic"]}",' for _, i in instrs]
    out += ["];", "", "/// Decode the opcode and funct of `word` ([DEC-1]). None means illegal.",
            "pub fn decode_op(word: u32) -> Option<Op> {", "    match word >> 26 {"]
    for g in spec["group"]:
        if g["format"] in ("R", "R4"):
            mask = 0x3FF if g["format"] == "R" else 0x1F
            out.append(f"        0x{g['opcode']:02X} => match word & 0x{mask:X} {{")
            for i in g["instructions"]:
                out.append(f"            0x{i['funct']:X} => Some(Op::{rust_variant(i['mnemonic'])}),")
            out += ["            _ => None,", "        },"]
        else:
            out.append(f"        0x{g['opcode']:02X} => Some(Op::{rust_variant(g['instructions'][0]['mnemonic'])}),")
    out += ["        _ => None,", "    }", "}", ""]
    uni = sum(1 << s["id"] for s in spec["sr"] if s["kind"] == "uniform")
    lane = sum(1 << s["id"] for s in spec["sr"] if s["kind"] == "lane")
    out += [f"/// Bit i set: special register i is uniform ([SR-1], [SR-2]).",
            f"pub const SR_UNIFORM: u32 = 0x{uni:08X};",
            f"/// Bit i set: special register i is per lane.",
            f"pub const SR_LANE: u32 = 0x{lane:08X};"]
    out += [f"pub const SR_{s['name']}: u32 = {s['id']};" for s in spec["sr"]]
    return "\n".join(out) + "\n"


SV_UNIT = {"SALU": "UNIT_SALU", "BRU": "UNIT_SALU", "SYS": "UNIT_SALU", "VALU": "UNIT_VALU",
           "FPU": "UNIT_FPU", "SFU": "UNIT_SFU", "LSU": "UNIT_LSU"}


def sv_op(mnemonic):
    return "OP_" + mnemonic.replace(".", "_")


def sv_text(spec):
    instrs = [(g, i) for g in spec["group"] for i in g["instructions"]]
    width = max(1, (len(instrs) - 1).bit_length())
    out = ["// Generated by tools/gen_isa.py from spec/isa.toml. Do not edit.",
           "// Op order matches rust/mgpu-core/src/isa_gen.rs; units match docs/uarch/core.md section 7.",
           "// A library package: not every constant is used by every design that imports it.",
           "/* verilator lint_off UNUSEDPARAM */",
           "package mgpu_isa_pkg;", "",
           f"  localparam int NUM_OPS = {len(instrs)};", "",
           f"  typedef enum logic [{width - 1}:0] {{"]
    out += [f"    {sv_op(i['mnemonic'])}{',' if k < len(instrs) - 1 else ''}" for k, (_, i) in enumerate(instrs)]
    out += ["  } op_e;", "",
            "  typedef enum logic [2:0] { UNIT_SALU, UNIT_VALU, UNIT_FPU, UNIT_SFU, UNIT_LSU } unit_e;", "",
            "  typedef struct packed {", "    logic valid;  // 0: illegal instruction ([DEC-1])",
            "    op_e  op;", "  } dec_t;", ""]
    out += [f"  localparam logic [5:0] OPC_{g['name']} = 6'h{g['opcode']:02X};" for g in spec["group"]]
    uni = sum(1 << s["id"] for s in spec["sr"] if s["kind"] == "uniform")
    lane = sum(1 << s["id"] for s in spec["sr"] if s["kind"] == "lane")
    out += ["", f"  localparam logic [31:0] SR_UNIFORM = 32'h{uni:08X};",
            f"  localparam logic [31:0] SR_LANE = 32'h{lane:08X};"]
    out += [f"  localparam logic [4:0] SR_{s['name']} = 5'd{s['id']};" for s in spec["sr"]]
    out += ["", "  // Opcode and full funct field select the instruction ([DEC-1]); the register and",
            "  // immediate fields never affect which instruction it is ([DEC-2]).",
            "  /* verilator lint_off UNUSEDSIGNAL */",
            "  function automatic dec_t decode_op(input logic [31:0] w);",
            "    dec_t d;", "    d.valid = 1'b1;", f"    d.op = {sv_op(instrs[0][1]['mnemonic'])};",
            "    unique case (w[31:26])"]
    for g in spec["group"]:
        if g["format"] in ("R", "R4"):
            hi = 9 if g["format"] == "R" else 4
            bits = hi + 1
            out.append(f"      6'h{g['opcode']:02X}:")
            out.append(f"        unique case (w[{hi}:0])")
            for i in g["instructions"]:
                out.append(f"          {bits}'h{i['funct']:X}: d.op = {sv_op(i['mnemonic'])};")
            out.append("          default: d.valid = 1'b0;")
            out.append("        endcase")
        else:
            out.append(f"      6'h{g['opcode']:02X}: d.op = {sv_op(g['instructions'][0]['mnemonic'])};")
    out += ["      default: d.valid = 1'b0;", "    endcase", "    return d;", "  endfunction",
            "  /* verilator lint_on UNUSEDSIGNAL */", "",
            "  function automatic unit_e unit_of(input op_e op);", "    unique case (op)"]
    by_unit: dict = {}
    for g, i in instrs:
        by_unit.setdefault(SV_UNIT[i.get("unit", g["unit"])], []).append(sv_op(i["mnemonic"]))
    for u, ops in by_unit.items():
        if u == "UNIT_SALU":
            continue
        out.append(f"      {', '.join(ops)}:")
        out.append(f"        return {u};")
    out += ["      default: return UNIT_SALU;", "    endcase", "  endfunction", "", "endpackage",
            "/* verilator lint_on UNUSEDPARAM */"]
    return "\n".join(out) + "\n"


def check_vectors(spec):
    sys.path.insert(0, str(ROOT / "python"))
    from mgpu.isa import assemble_one, decode
    errs = []
    for v in spec["vector"]:
        w = assemble_one(v["asm"])
        if w != v["hex"]:
            errs.append(f"vector {v['asm']!r}: got {w:#010x}, expected {v['hex']:#010x}")
        if decode(w).instr.mnemonic != v["asm"].split()[0].upper():
            errs.append(f"vector {v['asm']!r}: decode mismatch")
    return errs


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = ap.parse_args()
    spec = load()
    errors = validate(spec)
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    files = {ROOT / "python/mgpu/isa/tables.py": py_text(spec),
             ROOT / "docs/isa/encoding-tables.md": doc_text(spec),
             ROOT / "rust/mgpu-core/src/isa_gen.rs": rust_text(spec),
             ROOT / "rtl/pkg/mgpu_isa_pkg.sv": sv_text(spec)}
    stale = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
    else:
        for p, t in files.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(t)
    errors = check_vectors(spec)  # after writing, so tables.py is current
    for e in errors:
        print(e)
    n = sum(len(g["instructions"]) for g in spec["group"])
    print(f"{len(spec['group'])} opcodes, {n} instructions, {len(spec['vector'])} vectors checked"
          + ("" if args.check else f", {len(stale)} file(s) updated"))
    sys.exit(1 if errors or (args.check and stale) else 0)


if __name__ == "__main__":
    main()
